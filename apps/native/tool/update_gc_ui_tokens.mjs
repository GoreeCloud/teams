#!/usr/bin/env node
/**
 * Deterministic Flutter token adapter for a pinned, reviewed GoreeCloud UI
 * token snapshot. It NEVER fetches network data, installs dependencies,
 * executes external source or invents theme values.
 */
import {createHash} from "node:crypto";
import {readFileSync,writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";

const source=fileURLToPath(new URL("./gc-ui/gc.tokens.json",import.meta.url));
const target=fileURLToPath(new URL("../lib/generated/gc_ui_tokens.g.dart",import.meta.url));
const data=readFileSync(source);
const sha256=createHash("sha256").update(data).digest("hex");
const tokens=JSON.parse(data.toString("utf8"));
if(tokens.meta?.name!=="GoreeCloud UI"||tokens.meta?.license!=="MIT"||
   tokens.meta?.format!=="goreecloud-ui-alpha-1") {
  throw new Error("Unexpected canonical GoreeCloud UI schema");
}
const light=tokens.semantic.light,dark=tokens.semantic.dark;
const irisLight=tokens.accents.iris.light,irisDark=tokens.accents.iris.dark;
const roles={
  lightCanvas:light.canvas,
  darkCanvas:dark.canvas,
  lightSurface:light.surface,
  darkSurface:dark.surface,
  darkTonal:dark["surface-tonal"],
  lightText:light.text,
  darkText:dark.text,
  lightOutline:light.outline,
  darkOutline:dark.outline,
  lightError:light.negative,
  darkError:dark.negative,
  lightBrand:irisLight.brand,
  darkBrand:irisDark.brand,
  lightOnBrand:irisLight["on-brand"],
  darkOnBrand:irisDark["on-brand"],
  lightBrandContainer:irisLight["brand-container"],
  darkBrandContainer:irisDark["brand-container"],
  lightOnBrandContainer:irisLight["on-brand-container"],
  darkOnBrandContainer:irisDark["on-brand-container"]
};
const fields=Object.entries(roles).map(([name,value])=>{
  if(typeof value!=="string"||!/^#[\da-fA-F]{6}$/.test(value)) {
    throw new Error("Missing or invalid canonical color: "+name);
  }
  return "  static const "+name+" = Color(0xFF"+value.slice(1).toUpperCase()+");";
});
const output=[
  "// GENERATED by apps/native/tool/update_gc_ui_tokens.mjs. DO NOT EDIT.",
  "// Canonical: https://github.com/GoreeCloud/gc-ui/blob/5625121316230d78dd40a6e41a0671a250cb873b/tokens/gc.tokens.json",
  "// Source SHA-256: "+sha256,
  "// Approved alpha semantic roles and Iris accent, not a final design signoff.",
  "",
  "import 'package:flutter/material.dart';",
  "",
  "abstract final class GcUiTokenColors {",
  ...fields,
  "}",
  ""
].join("\n");
const command=process.argv.slice(2);
if(command.length!==1||!["--check","--write"].includes(command[0])) {
  throw new Error("Usage: node apps/native/tool/update_gc_ui_tokens.mjs --check|--write");
}
if(command[0]==="--write") {
  writeFileSync(target,output);
  console.log("Updated native Flutter colors from pinned GoreeCloud UI tokens");
}else {
  if(readFileSync(target,"utf8")!==output) {
    throw new Error("Native GoreeCloud UI generated tokens differ; run --write after reviewing upstream snapshot");
  }
  console.log("Native GoreeCloud UI tokens match pinned source SHA-256 "+sha256);
}
